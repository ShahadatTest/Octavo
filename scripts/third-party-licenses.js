// Generates THIRD_PARTY_LICENSES.md: every package that ends up in the shipped app (renderer
// bundle, main-process dependencies, Electron itself) with its license, the licenses of the
// pdf.js runtime assets copied next to the bundle, and the full license texts. The SIL Open Font
// License requires the font licenses to travel with the bundled fonts, so this file ships with
// every build (electron-builder.yml, extraResources).
//
// Run with: npm run licenses   (after changing dependencies)
const fs = require('node:fs')
const path = require('node:path')

const root = path.resolve(__dirname, '..')
const pkgJson = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'))

// Entry points that are actually distributed: what src/ imports. Everything reachable from them
// through `dependencies` is included. Dev tooling (vite, typescript, electron-builder, tsx, the
// fixture and test libraries) is not.
const SHIPPED = [
  'electron',
  'yauzl',
  'react',
  'react-dom',
  'zustand',
  'lucide-react',
  'foliate-js',
  'pdfjs-dist',
  '@fontsource-variable/inter',
  '@fontsource-variable/literata'
]
// Electron's own npm dependencies only serve to download the binary; the binary's notices
// (Chromium, Node, V8) ship inside Electron's distribution as LICENSES.chromium.html.
const NO_RECURSE = new Set(['electron'])

// Code other packages carry inside themselves without a license file of its own.
const VENDORED = [
  { name: 'zip.js', via: 'foliate-js/vendor/zip.js', license: 'BSD-3-Clause', url: 'https://github.com/gildas-lormeau/zip.js' },
  { name: 'fflate', via: 'foliate-js/vendor/fflate.js', license: 'MIT', url: 'https://github.com/101arrowz/fflate' },
  { name: 'QuickJS', via: 'pdfjs-dist/wasm/quickjs-eval.wasm', license: 'MIT', url: 'https://bellard.org/quickjs/' }
]

// pdf.js fetches these at run time; scripts/copy-pdfjs-assets.js copies them next to the bundle.
const PDFJS_ASSETS = [
  ['Standard fonts: Foxit', 'standard_fonts/LICENSE_FOXIT'],
  ['Standard fonts: Liberation', 'standard_fonts/LICENSE_LIBERATION'],
  ['CMaps', 'cmaps/LICENSE'],
  ['ICC colour profile', 'iccs/LICENSE'],
  ['JBIG2 decoder', 'wasm/LICENSE_JBIG2'],
  ['JBIG2 decoder: pdf.js build', 'wasm/LICENSE_PDFJS_JBIG2'],
  ['OpenJPEG decoder', 'wasm/LICENSE_OPENJPEG'],
  ['OpenJPEG decoder: pdf.js build', 'wasm/LICENSE_PDFJS_OPENJPEG'],
  ['QCMS colour management', 'wasm/LICENSE_QCMS'],
  ['QCMS colour management: pdf.js build', 'wasm/LICENSE_PDFJS_QCMS']
]

const seen = new Map()
function visit(name) {
  if (seen.has(name)) return
  const dir = path.join(root, 'node_modules', name)
  let pkg
  try {
    pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'))
  } catch {
    console.warn(`warning: ${name} is not installed`)
    return
  }
  seen.set(name, { dir, pkg })
  if (NO_RECURSE.has(name)) return
  for (const dep of Object.keys(pkg.dependencies || {})) visit(dep)
}
SHIPPED.forEach(visit)

const read = (file) => fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n').trim()

function licenseText(dir) {
  for (const file of fs.readdirSync(dir)) {
    if (/^(license|licence|copying|ofl)(\.|-|$)/i.test(file) && fs.statSync(path.join(dir, file)).isFile()) {
      return read(path.join(dir, file))
    }
  }
  return null
}

const licenseOf = (pkg) => (typeof pkg.license === 'string' ? pkg.license : pkg.license?.type || (pkg.licenses || []).map((l) => l.type).join(' OR ') || 'see package')

const entries = [...seen.values()].sort((a, b) => a.pkg.name.localeCompare(b.pkg.name))
const missing = []
const pdfjs = path.join(root, 'node_modules', 'pdfjs-dist')
const assets = PDFJS_ASSETS.filter(([, file]) => {
  if (fs.existsSync(path.join(pdfjs, file))) return true
  console.warn(`warning: pdfjs-dist has no ${file}`)
  return false
})

let out = `# Third-party notices\n\n`
out += `Octavo ${pkgJson.version} is licensed under the GNU General Public License v3.0 or later (see LICENSE).\n`
out += `It bundles the open-source packages, fonts and pdf.js assets below. Their licenses are reproduced in full further down.\n`
out += `This file is generated by \`npm run licenses\`; do not edit it by hand.\n\n`
out += `The bundled typefaces Inter and Literata are licensed under the SIL Open Font License 1.1.\n`
out += `Electron's Chromium, Node.js and V8 notices are distributed with the Electron binary itself (LICENSES.chromium.html).\n\n`
out += `| Package | Version | License |\n|---|---|---|\n`
for (const { pkg } of entries) out += `| ${pkg.name} | ${pkg.version} | ${licenseOf(pkg)} |\n`
for (const v of VENDORED) out += `| ${v.name} (in ${v.via}) | | ${v.license} |\n`
out += `\n## License texts\n`
for (const { dir, pkg } of entries) {
  const text = licenseText(dir)
  if (!text) {
    missing.push(pkg.name)
    continue
  }
  out += `\n---\n\n### ${pkg.name} ${pkg.version} (${licenseOf(pkg)})\n\n\`\`\`\n${text}\n\`\`\`\n`
}
for (const [label, file] of assets) {
  out += `\n---\n\n### pdfjs-dist: ${label} (${file})\n\n\`\`\`\n${read(path.join(pdfjs, file))}\n\`\`\`\n`
}
out += `\n---\n\nCarried inside the packages above without a license file of their own: `
out += VENDORED.map((v) => `${v.name} (${v.license}, ${v.url})`).join('; ') + '.\n'
if (missing.length) {
  out += `\nPackages whose license text is not included in their npm distribution (license declared in package.json): ${missing.join(', ')}.\n`
}

fs.writeFileSync(path.join(root, 'THIRD_PARTY_LICENSES.md'), out)
console.log(`${entries.length} packages and ${assets.length} pdf.js asset licenses listed, ${entries.length - missing.length} package license texts included`)
if (missing.length) console.log(`no license file shipped for: ${missing.join(', ')}`)
